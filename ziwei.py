"""南派核盘用命身、宫干、主辅星与生年四化。"""
G='甲乙丙丁戊己庚辛壬癸'; Z='子丑寅卯辰巳午未申酉戌亥'
PAL=['命宫','兄弟','夫妻','子女','财帛','疾厄','迁移','交友','官禄','田宅','福德','父母']
_ny=list('金火木土金火水土金木水土火木水金火木土金火水土金木水土火木水')
JU={'水':2,'木':3,'金':4,'土':5,'火':6}
SIHUA_FX={'甲':['廉贞','破军','武曲','太阳'],'乙':['天机','天梁','紫微','太阴'],'丙':['天同','天机','文昌','廉贞'],'丁':['太阴','天同','天机','巨门'],'戊':['贪狼','太阴','右弼','天机'],'己':['武曲','贪狼','天梁','文曲'],'庚':['太阳','武曲','太阴','天同'],'辛':['巨门','太阳','文曲','文昌'],'壬':['天梁','紫微','左辅','武曲'],'癸':['破军','巨门','太阴','贪狼']}

def gz60(s,b):
    return next(i for i in range(60) if i%10==s and i%12==b)

def chart(ys,yb,m,d,h):
    st={}
    def put(name,pos): st.setdefault(pos%12,[]).append(name)
    ming=(2+(m-1)-h)%12; shen=(2+(m-1)+h)%12
    s0={0:2,5:2,1:4,6:4,2:6,7:6,3:8,8:8,4:0,9:0}[ys]
    def pstem(b): return (s0+(b-2)%12)%10
    ju=JU[_ny[gz60(pstem(ming),ming)//2]]
    x=(-d)%ju
    q=(d+x)//ju; zw=(2+q-1+(-x if x%2 else x))%12
    for n,o in [('紫微',0),('天机',-1),('太阳',-3),('武曲',-4),('天同',-5),('廉贞',-8)]: put(n,zw+o)
    F=(4-zw)%12
    for n,o in [('天府',0),('太阴',1),('贪狼',2),('巨门',3),('天相',4),('天梁',5),('七杀',6),('破军',10)]: put(n,F+o)
    put('左辅',4+(m-1)); put('右弼',10-(m-1)); put('文昌',10-h); put('文曲',4+h)
    lc={0:2,1:3,2:5,3:6,4:5,5:6,6:8,7:9,8:11,9:0}[ys]; put('禄存',lc); put('擎羊',lc+1); put('陀罗',lc-1)
    kui,yue={0:(1,7),4:(1,7),6:(1,7),1:(0,8),5:(0,8),2:(11,9),3:(11,9),7:(6,2),8:(3,5),9:(3,5)}[ys]; put('天魁',kui); put('天钺',yue)
    put('地劫',11+h); put('地空',11-h)
    grp={2:'a',6:'a',10:'a',8:'b',0:'b',4:'b',5:'c',9:'c',1:'c',11:'d',3:'d',7:'d'}[yb]
    f0,l0={'a':(1,3),'b':(2,10),'c':(3,10),'d':(9,10)}[grp]; put('火星',f0+h); put('铃星',l0+h)
    put('天马',{'a':8,'b':2,'c':11,'d':5}[grp]); hl=(3-yb)%12; put('红鸾',hl); put('天喜',hl+6)
    put('天刑',9+(m-1)); put('天姚',1+(m-1)); put('天空',yb+1)
    sh=dict(zip(SIHUA_FX[G[ys]],['禄','权','科','忌']))
    rows=[]
    for k in range(12):
        b=(ming-k)%12
        stars=[s+('('+sh[s]+')' if s in sh else '') for s in st.get(b,[])]
        rows.append((PAL[k],G[pstem(b)]+Z[b],('身' if b==shen else ''),' '.join(stars)))
    return ming,shen,ju,rows,pstem
